const scriptDir = path.resolve(`scripts/${COURSE_ID}`);
const slideDir = path.resolve(`slides/${COURSE_ID}`);
fs.mkdirSync(scriptDir, { recursive: true });
fs.mkdirSync(slideDir, { recursive: true });

let yaml = `# 手動作成（${COURSE_ID}）。AI駆動副業。実際に運用している仕組みを題材にする。
id: ${COURSE_ID}
title: ${COURSE_TITLE}
speakerId: 2
silenceDuration: 0.5
audioLayout: nested
lessons:
`;

const mismatches = L.filter(([, , , , sections, pages]) => sections.length !== pages.length + 1)
  .map(([, file, , , sections, pages]) => `${file}: sections=${sections.length} pages=${pages.length} (pages は ${sections.length - 1} にする)`);
if (mismatches.length) {
  console.error('ページ数が台本の区切り数と合いません:\n' + mismatches.join('\n'));
  process.exit(1);
}

for (const [id, file, name, sub, sections, pages] of L) {
  fs.writeFileSync(path.join(scriptDir, `${file}.txt`), sections.join('\n---\n') + '\n', 'utf8');
  let md = HEADER + `\n# ${name}\n\n**${sub}**\n`;
  for (const [h, body] of pages) md += `\n---\n\n## ${h}\n\n${body}\n`;
  fs.writeFileSync(path.join(slideDir, `${file}.md`), md, 'utf8');
  yaml += `  - id: ${id}\n    title: "${name}"\n    script: scripts/${COURSE_ID}/${file}.txt\n    slide: slides/${COURSE_ID}/${file}.md\n`;
}
fs.writeFileSync(path.resolve(`courses/${COURSE_ID}.yaml`), yaml, 'utf8');
console.log(`generated ${L.length} lessons (scripts + slides) and courses/${COURSE_ID}.yaml`);
